// frontend/lib/passwords.ts
/**
 * Temporary vendor-review passwords for Added product pages: one row per
 * product, keyed by exact `product_name`, in the Firestore `passwords`
 * document. Pure helpers only -- no I/O in this module.
 *
 * Kept outside lib/server/documents.ts's DataKind ETag/If-Match system:
 * every writer is server-side, so instead of a client If-Match round trip
 * app writes are atomic read-modify-writes through mutatePasswords
 * (lib/server/passwords-store.ts -- read, modify and write in one Firestore
 * transaction). The exception is the mirror promote, which deletes password
 * rows inside its own transaction (transactDocuments, D40) and creates none
 * (D6). Scripts outside frontend/ (scripts/nerd_documents.py push,
 * scripts/write_single_document.py) can still overwrite the document
 * directly.
 *
 * Passwords are generated by getOrCreatePassword (below) at Candidate
 * import, and can be edited afterwards. The mirror promote (promote-live)
 * creates none (D6); it only deletes rows, inside its own transaction (D40).
 * setPassword (below) backs PUT /api/local/passwords, used by
 * components/PasswordField.tsx in both the Added and Candidate editors. A
 * row's `timestamp` therefore means "last set", not "first created".
 *
 * Generation pattern (exact spec): the first four letters of the product
 * name, spaces stripped and lowercased, immediately followed by the
 * two-digit current year (no separator), e.g. "MLC Number Chart" ->
 * "mlcn26". A second product colliding on that same base (e.g. "MLC
 * Number Pieces" -> also "mlcn") gets a numeric suffix starting at 1
 * ("mlcn26-1"), incrementing past any suffix that's already taken too --
 * the FIRST record to claim a base keeps it unsuffixed forever; later
 * collisions never renumber it.
 */

export interface PasswordRecord {
  product_name: string;
  vendor_name: string | null;
  password: string;
  timestamp: string;
}

/** First four letters of `productName` with spaces stripped and
 *  lowercased, e.g. "MLC Number Chart" -> "mlcn". Non-space characters
 *  only are counted toward the four -- punctuation/digits in a product
 *  name still consume a slot, matching "first four letters" read as
 *  "first four characters of the space-stripped name" rather than
 *  filtering to strictly alphabetic characters, since the spec's own
 *  example product names are plain words with no such characters to
 *  disambiguate against. */
function baseSlug(productName: string): string {
  return productName.replace(/\s+/g, "").toLowerCase().slice(0, 4);
}

function twoDigitYear(now: Date): string {
  return String(now.getFullYear() % 100).padStart(2, "0");
}

/** Finds the next unused password for `base` (e.g. "mlcn26") against
 *  `existingPasswords` -- `base` itself if free, else `${base}-1`,
 *  `${base}-2`, ... incrementing past whatever's already taken. */
function nextAvailablePassword(base: string, existingPasswords: Set<string>): string {
  if (!existingPasswords.has(base)) return base;
  let suffix = 1;
  while (existingPasswords.has(`${base}-${suffix}`)) {
    suffix += 1;
  }
  return `${base}-${suffix}`;
}

/**
 * Returns the password for `productName`, creating and appending one to
 * `records` if none exists yet. Matched by exact `product_name` string --
 * the same field/matching convention the rest of this app uses for
 * cross-referencing a product to its global vendor entry (see
 * CandidateEditor.tsx's VENDORS_REGISTRY lookup). Pure function: the
 * caller (POST /api/local/passwords, through mutatePasswords) owns
 * persisting `records` when `created` is true.
 */
export function getOrCreatePassword(
  records: PasswordRecord[],
  productName: string,
  vendorName: string | null,
  now: Date = new Date()
): { records: PasswordRecord[]; record: PasswordRecord; created: boolean } {
  const existing = records.find((r) => r.product_name === productName);
  if (existing) {
    return { records, record: existing, created: false };
  }

  const base = `${baseSlug(productName)}${twoDigitYear(now)}`;
  const existingPasswords = new Set(records.map((r) => r.password));
  const password = nextAvailablePassword(base, existingPasswords);

  const record: PasswordRecord = {
    product_name: productName,
    vendor_name: vendorName,
    password,
    timestamp: now.toISOString(),
  };

  return { records: [...records, record], record, created: true };
}

/**
 * Sets `productName`'s password to exactly `password`, creating the row if
 * none exists. Matched by exact `product_name` string, the same convention
 * as getOrCreatePassword above. Pure function: never mutates `records` or
 * any record in it, and callers own persisting the returned `records` when
 * `changed` is true.
 *
 * - Existing row, same password: input returned as-is, `changed: false`.
 * - Existing row, different password: a NEW array with that row replaced;
 *   its `vendor_name` is kept (the `vendorName` argument is ignored here).
 * - No row: one appended, `created: true`.
 *
 * No trimming or validation here -- the route owns input validation. No
 * uniqueness check against other rows' passwords: duplicates are allowed by
 * decision. On an edited row `timestamp` now means "last set", not "first
 * created" -- a deliberate change in that field's meaning.
 */
export function setPassword(
  records: PasswordRecord[],
  productName: string,
  password: string,
  vendorName: string | null,
  now: Date
): { records: PasswordRecord[]; record: PasswordRecord; created: boolean; changed: boolean } {
  const index = records.findIndex((r) => r.product_name === productName);

  if (index !== -1) {
    const existing = records[index];
    if (existing.password === password) {
      return { records, record: existing, created: false, changed: false };
    }
    const record: PasswordRecord = { ...existing, password, timestamp: now.toISOString() };
    const next = records.slice();
    next[index] = record;
    return { records: next, record, created: false, changed: true };
  }

  const record: PasswordRecord = {
    product_name: productName,
    vendor_name: vendorName,
    password,
    timestamp: now.toISOString(),
  };
  return { records: [...records, record], record, created: true, changed: true };
}
